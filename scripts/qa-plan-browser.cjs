const { chromium, expect } = require('@playwright/test');
const fs = require('fs');
const assert = require('assert/strict');
(async () => {
  const accounts = JSON.parse(fs.readFileSync(process.env.QA_CREDENTIALS_FILE || '/tmp/sls240-browser-credentials.json'));
  const a = accounts.find(a => a.plan === 'starter' && a.interval === 'year');
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ baseURL: process.env.QA_BASE_URL || 'http://localhost:5273' });
  const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  fs.mkdirSync('/tmp/sls240-qa', { recursive: true });
  try {
    async function confirmButton(name) {
      await expect(page.getByRole('button', { name })).toBeEnabled();
      const response = page.waitForResponse(r => /\/billing\/changes\/[^/]+\/confirm$/.test(r.url()) && r.request().method() === 'POST');
      await page.getByRole('button', { name }).click();
      const body = await (await response).json(); assert(body.success, JSON.stringify(body)); assert.equal(body.data.status, 'succeeded');
    }
    await page.goto('/');
    await expect(page.getByRole('heading', { name: 'Starter', exact: true })).toBeVisible();
    await page.getByRole('radio', { name: /Annual/ }).check();
    await expect(page.getByText('$990.00/year', { exact: true })).toBeVisible();
    await expect(page.getByText('$1,990.00/year', { exact: true })).toBeVisible();
    await expect(page.getByText('$3,990.00/year', { exact: true })).toBeVisible();
    await expect(page.getByText(/Get twelve months for the price of ten/)).toBeVisible();
    await page.screenshot({ path: '/tmp/sls240-qa/pricing-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: '/tmp/sls240-qa/pricing-mobile.png', fullPage: true });
    await page.goto('/register?plan=multi&interval=year');
    await expect(page.getByRole('radio', { name: /Annual/ })).toBeChecked();
    await expect(page.getByRole('button', { name: 'Selected', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await expect(page.getByText('$3,990.00/year', { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 1280, height: 960 });
    await page.goto('/login');
    await page.locator('input[type=email]').fill(a.email); await page.locator('input[type=password]').fill(a.password);
    const login = page.waitForResponse(r => r.url().endsWith('/api/auth/login') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    const auth = await (await login).json(); const headers = { Authorization: `Bearer ${auth.data.accessToken}` };
    await page.waitForURL(/dashboard/);
    await page.goto('/dashboard/settings?tab=billing');
    const section = page.getByRole('region', { name: 'Change subscription' });
    await section.getByRole('button', { name: 'Change plan or billing interval' }).click();
    await section.getByRole('button', { name: 'Choose Pro', exact: true }).click();
    await section.getByRole('radio', { name: /Annual/ }).check();
    await section.getByRole('textbox', { name: 'Promo code', exact: true }).fill(a.promo);
    await section.getByRole('button', { name: 'Preview change', exact: true }).click();
    await expect(section.getByTestId('change-due-today')).toHaveText('$0.00');
    await expect(section.getByText(/Two months free: twelve months/)).toBeVisible();
    await confirmButton(/Confirm plan change/);
    await expect(section.getByRole('status')).toContainText('updated');
    const status = await (await context.request.get('/api/billing/status', { headers })).json(); assert.equal(status.data.planKey, 'pro'); assert.equal(status.data.interval, 'year');
    await expect(page.getByText('Pro plan · active')).toBeVisible();
    await section.getByRole('button', { name: 'Add location', exact: true }).click();
    await section.getByRole('textbox', { name: 'Promo code', exact: true }).fill(a.promo);
    await section.getByRole('button', { name: 'Preview change', exact: true }).click();
    await expect(section.getByTestId('change-due-today')).toHaveText('$0.00');
    await expect(section.getByText('$2,780.00/year', { exact: true })).toBeVisible();
    await confirmButton(/Confirm additional location/);
    await expect(section.getByRole('status')).toContainText('updated');
    const created = await (await context.request.post('/api/locations', { headers, data: { name: 'Browser chosen removal' } })).json(); assert(created.success, JSON.stringify(created));
    await page.reload();
    await section.getByRole('button', { name: 'Change plan or billing interval' }).click();
    await section.getByRole('button', { name: 'Choose Starter', exact: true }).click();
    await expect(section.getByRole('button', { name: 'Preview change', exact: true })).toBeDisabled();
    await expect(section.getByRole('checkbox', { name: 'Keep this location' })).not.toBeChecked();
    await section.getByRole('checkbox', { name: 'Browser chosen removal' }).check();
    await section.getByRole('textbox', { name: 'Promo code', exact: true }).fill(a.promo);
    await section.getByRole('button', { name: 'Preview change', exact: true }).click();
    await expect(section.getByText('Confirming permanently removes: Browser chosen removal.')).toBeVisible();
    await page.screenshot({ path: '/tmp/sls240-qa/downgrade-selection.png', fullPage: true });
    await confirmButton(/Confirm plan change/);
    await expect(section.getByRole('status')).toContainText('updated');
    const locations = await (await context.request.get('/api/locations', { headers })).json(); assert.equal(locations.data.length, 1); assert.equal(locations.data[0].id, a.locationId);
    await page.goto('/dashboard/citations'); await expect(page.getByRole('link', { name: /Upgrade to Pro/ })).toBeVisible();
    await page.goto('/dashboard/rankings'); await page.getByRole('button', { name: /Visibility Map/ }).click();
    await expect(page.getByText(/Failed to/)).toHaveCount(0);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ pricingDesktop: 'passed', pricingMobile: 'no overflow', registerAnnual: 'passed', annualUpgrade: 'passed', annualAddon: 'passed', downgradeSelection: 'required and respected', starterMap: 'visible', lockedFeature: 'upgrade prompt', javascriptErrors: errors.length }));
  } catch (e) { await page.screenshot({ path: '/tmp/sls240-qa/failure.png', fullPage: true }); throw e; }
  finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
