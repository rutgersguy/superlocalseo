const assert = require('assert/strict');
const { db } = require('/app/dist/db/connection');
const { stripe, handleWebhookEvent } = require('/app/dist/services/stripe.service');
const { config } = require('/app/dist/config');
const fs = require('fs');
async function api(a, path, body, method = 'POST') { const r = await fetch(`http://localhost:3000/api${path}`, { method, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${a.token}` }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }); return { status: r.status, ...await r.json() }; }
async function request(a, path, body, method) { const r = await api(a, path, body, method); assert(r.success, JSON.stringify(r)); return r.data; }
(async () => {
  assert(config.stripe.secretKey.startsWith('sk_test_'));
  const accounts = JSON.parse(fs.readFileSync('/tmp/sls240-browser-credentials.json'));
  for (const a of accounts) a.token = (await request(a, '/auth/login', { email: a.email, password: a.password })).accessToken;
  const a = accounts[2];
  let q = await request(a, '/billing/changes/preview', { action: 'change_plan', plan: 'multi', interval: 'year', capacity: 3 });
  assert(q.amountDue > 0); assert(q.needsCard);
  assert.equal((await api(a, `/billing/changes/${q.id}/confirm`, {})).status, 400);
  await request(a, `/billing/changes/${q.id}/setup`, {});
  const row = await db('billing_changes').where({ id: q.id }).first();
  await stripe.setupIntents.confirm(row.setup_intent_id, { payment_method: 'pm_card_visa' });
  const result = await request(a, `/billing/changes/${q.id}/confirm`, {}); assert.equal(result.status, 'succeeded');
  assert.equal((await stripe.invoices.retrieve(result.invoiceId)).amount_due, q.amountDue);
  const b = accounts[3];
  const card = await stripe.paymentMethods.attach('pm_card_chargeCustomerFail', { customer: b.customerId });
  await stripe.subscriptions.update(b.subscriptionId, { default_payment_method: card.id });
  q = await request(b, '/billing/changes/preview', { action: 'change_plan', plan: 'multi', interval: 'year', capacity: 3 });
  const failed = await request(b, `/billing/changes/${q.id}/confirm`, {}); assert.equal(failed.status, 'payment_required');
  assert.equal((await db('clients').where({ id: b.clientId }).first()).plan_key, 'pro');
  assert.equal((await request(b, '/billing/changes/pending', undefined, 'GET')).id, q.id);
  await request(b, `/billing/changes/${q.id}`, undefined, 'DELETE');
  assert.equal((await stripe.subscriptions.retrieve(b.subscriptionId)).pending_update, null);
  const c = accounts[4]; const before = await stripe.subscriptions.retrieve(c.subscriptionId);
  await db('clients').where({ id: c.clientId }).update({ pricing_version: 'legacy' });
  assert.equal((await api(c, '/billing/changes/preview', { action: 'change_plan', plan: 'pro', interval: 'month' })).status, 409);
  assert.deepEqual((await stripe.subscriptions.retrieve(c.subscriptionId)).items, before.items);
  await db('clients').where({ id: c.clientId }).update({ pricing_version: '2026-10' });
  const d = accounts[5];
  q = await request(d, '/billing/changes/preview', { action: 'change_plan', plan: 'pro', interval: 'year', capacity: 3 });
  const [loc] = await db('locations').insert({ client_id: d.clientId, name: 'New location after preview' }).returning('*');
  assert.equal((await api(d, `/billing/changes/${q.id}/confirm`, {})).status, 409);
  await db('locations').where({ id: loc.id }).delete();
  await db('billing_changes').where({ id: q.id }).update({ expires_at: new Date(0) });
  assert.equal((await api(d, `/billing/changes/${q.id}/confirm`, {})).status, 409);
  const sub = await stripe.subscriptions.update(d.subscriptionId, { cancel_at_period_end: true });
  await handleWebhookEvent({ type: 'customer.subscription.updated', data: { object: sub } });
  assert.equal((await db('clients').where({ id: d.clientId }).first()).subscription_status, 'active');
  const canceled = await stripe.subscriptions.cancel(d.subscriptionId);
  await handleWebhookEvent({ type: 'customer.subscription.deleted', data: { object: canceled } });
  assert.equal((await db('clients').where({ id: d.clientId }).first()).subscription_status, 'canceled');
  console.log(JSON.stringify({ noCard: 'SetupIntent and confirm passed', declinedPayment: 'old plan retained; pending change canceled', legacy: 'Stripe items unchanged', staleLocations: 'blocked', expiredPreview: 'blocked', scheduledCancel: 'access retained', cancellation: 'access revoked' }));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => db.destroy());
